function iconSVG(key, size) {
  const sp = SPRITES[key] || SPRITES.sprout; let r = '';
  for (let y = 0; y < 12; y++) { const row = (sp[y] || '').padEnd(12, '.'); for (let x = 0; x < 12; x++) { const c = row[x]; if (c !== '.' && PAL[c]) r += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${PAL[c]}"/>`; } }
  return `<svg class="pxicon" viewBox="0 0 12 12" width="${size}" height="${size}" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}

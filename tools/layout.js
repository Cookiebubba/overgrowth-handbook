#!/usr/bin/env node
// Builds layout.js: a radial "tidy tree" growing out of the center node, like GrassChopper's vine tree.
// Each node is placed under ONE primary parent (same-arc parent preferred); other requirements are drawn as thinner vines.
const fs = require('fs');
eval(fs.readFileSync(__dirname + '/../skills-data.js', 'utf8').replace(/^const /gm, 'var '));
const byId = Object.fromEntries(SKILLS.map(s => [s.id, s]));
const deps = n => [...n.all, ...n.any.flat()];
const dm = {}; const depth = id => id in dm ? dm[id] : (dm[id] = (() => { const n = byId[id]; let d = 0; for (const a of n.all) d = Math.max(d, depth(a) + 1); for (const g of n.any) d = Math.max(d, Math.min(...g.map(x => depth(x) + 1))); return d; })());
const ARC_ORDER = Object.keys(ARCS);
const root = SKILLS.find(n => !deps(n).length).id;
const parent = {};
for (const n of SKILLS) { if (n.id === root) continue; const c = deps(n).map(id => byId[id]);
  c.sort((a, b) => (b.arc === n.arc) - (a.arc === n.arc) || (n.all.includes(b.id)) - (n.all.includes(a.id)) || depth(b.id) - depth(a.id));
  parent[n.id] = c[0].id; }
const kids = {}; SKILLS.forEach(n => kids[n.id] = []); for (const [c, p] of Object.entries(parent)) kids[p].push(c);
const arcIdx = id => ARC_ORDER.indexOf(byId[id].arc);
for (const k of Object.values(kids)) k.sort((a, b) => arcIdx(a) - arcIdx(b) || leaves(b) - leaves(a));
function leaves(id) { return kids[id].length ? kids[id].reduce((s, c) => s + leaves(c), 0) : 1; }
const P = {}, tdepth = {}; const STEP = 150;
function place(id, a0, a1, d) { const a = (a0 + a1) / 2, r = d === 0 ? 0 : 40 + d * STEP; P[id] = [r * Math.cos(a), r * Math.sin(a)]; tdepth[id] = d;
  const tot = leaves(id); let cur = a0; for (const c of kids[id]) { const w = (a1 - a0) * leaves(c) / tot; place(c, cur, cur + w, d + 1); cur += w; } }
const START = Math.PI * 0.62; // discover starts lower-left and wraps clockwise
place(root, START, START + Math.PI * 2, 0);
// relax overlaps only
const ids = Object.keys(P);
for (let it = 0; it < 300; it++) for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) {
  const a = P[ids[i]], b = P[ids[j]]; let dx = b[0] - a[0], dy = b[1] - a[1], d = Math.hypot(dx, dy) || 1; const min = 150;
  if (d < min) { const f = (min - d) / d * .5; if (ids[i] !== root) { a[0] -= dx * f; a[1] -= dy * f; } if (ids[j] !== root) { b[0] += dx * f; b[1] += dy * f; } } }
const M = 140, xs = ids.map(i => P[i][0]), ys = ids.map(i => P[i][1]), minX = Math.min(...xs) - M, minY = Math.min(...ys) - M;
const pos = {}; ids.forEach(i => pos[i] = [Math.round(P[i][0] - minX), Math.round(P[i][1] - minY)]);
const W = Math.round(Math.max(...xs) - minX + M), H = Math.round(Math.max(...ys) - minY + M);
fs.writeFileSync(__dirname + '/../layout.js', `// generated by tools/layout.js (do not edit by hand)\nconst LAYOUT = ${JSON.stringify({ W, H, pos, parent, depth: dm })};\n`);
console.log('layout', W, 'x', H, 'tree depth', Math.max(...Object.values(tdepth)));
